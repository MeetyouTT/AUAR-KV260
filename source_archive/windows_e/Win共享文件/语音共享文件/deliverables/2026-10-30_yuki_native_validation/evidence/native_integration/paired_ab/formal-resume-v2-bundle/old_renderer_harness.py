"""Fresh-r3 remote16 / diagnostic remote-noJPEG16 / native Yuki16 pair.

Default check-only has no RPC, display, Gst or renderer work. The coordinator
must explicitly execute inside its reserved resource window. Never production
8796, live selected/config changes, physical audio/camera, or model service calls.
"""
import time
PROCESS_STARTED=time.monotonic()
from pathlib import Path
from collections import deque
import argparse
import importlib
import json
import math
import os
import random
import sys
sys.dont_write_bytecode=True

def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__)
    for key in ('runtime','board-manifest','fresh-baseline','server-proof','scenario','pcm','envelope'):
        parser.add_argument('--'+key,type=Path,required=True)
    parser.add_argument('--output',type=Path)
    parser.add_argument('--window',type=Path,help='Common A/B opaque in-screen window JSON')
    parser.add_argument('--backend',choices=('old','old_nojpeg','new'),default='old')
    parser.add_argument('--candidate-aura',type=Path,help='Isolated B root containing tools and assets/yuki')
    parser.add_argument('--candidate-manifest',type=Path,help='Frozen ui_candidate manifest for B overlay')
    parser.add_argument('--yuki-root',type=Path,help='Prepared isolated Yuki {root,config,files} JSON')
    parser.add_argument('--startup-timeout',type=float,default=90.)
    parser.add_argument('--execute',action='store_true')
    args=parser.parse_args(argv)
    legacy=args.backend!='new'
    sys.path.insert(0,str(Path(__file__).resolve().parent))
    from old_harness_support import (preflight,read_scenario,sha,PreparedPcmJobs,FakesinkOutput,
        create_controller,candidate_sources,load_candidate_tools,swap_tail_stats,NoPreviewEncoder)
    plan=preflight(args.runtime,args.board_manifest,args.fresh_baseline,args.server_proof)
    scenario=read_scenario(args.scenario)
    check=dict(schema='aura.paired_ab.renderer.v1',status='CHECKED_NO_EXECUTION',
        backend='fresh-r3-remote16',size=[423,438],target_fps=16,
        production_port=plan['production_port'],isolated_port=plan['isolated_port'],
        harness_hashes={name:sha(Path(__file__).resolve().parent/name) for name in
            ('paired_renderer_harness.py','old_renderer_harness.py','old_harness_support.py')},
        revision=plan['remote']['revision'],source_hashes=plan['hashes'],
        config_sha256=plan['config_sha256'],scenario_sha256=sha(args.scenario),
        pcm_sha256=sha(args.pcm),envelope_sha256=sha(args.envelope),
        production_modified=False,physical_audio=False,camera_opened=False,model_service_called=False,source_patches=[],
        features=dict(native_pixels=True,native_pixel_threads=3,old_eight_state_prewarm=True,
            actual_realtime_controller=True,actual_avatar_render_worker=True,frame_presenter=True,
            preview_jpeg='original latest-only >=0.2sec quality85',native_video=True,
            full_business_ui=False,common_background_camera='coordinator-owned'))
    candidate_aura=None;candidate_config=None;candidate_paths=None
    if args.backend=='new':
        if args.yuki_root is None and args.candidate_aura is None:raise ValueError('New backend requires --yuki-root or --candidate-aura')
        candidate_aura,candidate_hashes,candidate_config,candidate_paths=candidate_sources(args.candidate_aura,args.candidate_manifest,args.yuki_root)
        check.update(backend='new-yuki-native16',candidate_aura=str(candidate_aura),candidate_source_hashes=candidate_hashes,
            candidate_python_paths={k:str(v) for k,v in candidate_paths.items()})
        check['features'].update(native_pixels=False,native_pixel_threads=None,old_eight_state_prewarm=False,
            frame_presenter=False,preview_jpeg='not generated by the actual candidate _native_yuki path',
            native_video=False,public_snapshot_cadence='candidate worker per rendered frame16Hz',
            added_observer='frame_observer dict(stats)+append paint_at scalar to240 deque; counted in B')
    else:
        check['features']['public_snapshot_cadence']='old native-video worker at most10Hz'
        if args.backend=='old_nojpeg':
            check['backend']='fresh-r3-remote16-nojpeg-control'
            check['diagnostic_control_only']=True
            check['features']['preview_jpeg']='truthy no-op object; read returns empty bytes; no encoder thread'
            check['source_patches']=[dict(scope='this isolated Python process only; no source file edits',
                module='tools.board_avatar_worker',symbol='PreviewEncoder',applied_before='AvatarRenderWorker construction',
                original_source_sha256=plan['hashes']['tools/board_avatar_worker.py'],
                replacement='old_harness_support.NoPreviewEncoder',replacement_source_sha256=check['harness_hashes']['old_harness_support.py'],
                methods=dict(__bool__='True',offer='no-op',offer_rgb='no-op',read="b''",close='no-op'),
                rationale='keep truthy branch to avoid synchronous PIL JPEG fallback; leave RGB, presenter, Gst, logs and public throttle intact')]
    if not args.execute:print(json.dumps(check,ensure_ascii=True),flush=True);return 0
    if args.output is None or args.window is None:raise ValueError('--execute requires dedicated --output and common --window')
    output_dir=args.output.resolve(strict=False)
    # All benchmark writes are under a new dedicated directory, outside the
    # immutable runtime. No existing result or production path is overwritten.
    if (output_dir.is_relative_to(plan['runtime']) or output_dir.exists() or
        candidate_aura is not None and output_dir.is_relative_to(candidate_aura)):
        raise ValueError('Output must be a new directory outside immutable runtime inputs')
    window_plan=json.loads(args.window.read_text(encoding='utf8'))
    x,y=window_plan.get('x',590),window_plan.get('y',80)
    if (type(x)is not int or type(y)is not int or x<0 or y<0 or x+423>1024 or y+438>600 or
        window_plan.get('width',423)!=423 or window_plan.get('height',438)!=438 or
        window_plan.get('opacity',1)!=1 or window_plan.get('accept_focus',False)):
        raise ValueError('Expected same opaque non-focus in-screen423x438 window')
    output_dir.mkdir(parents=True,exist_ok=False)
    check.update(pid=os.getpid(),process_start_monotonic=PROCESS_STARTED,window=window_plan,
                 window_sha256=sha(args.window),started_monotonic=time.monotonic(),status='INITIALIZING')
    (output_dir/'run-plan.json').write_text(json.dumps(check,indent=2),encoding='utf8')
    print('PAIRED '+json.dumps(check,ensure_ascii=True),flush=True)
    random.seed(int(scenario.get('seed',1)))
    sys.path.insert(0,str(plan['aura']))
    # Load the real board Gst implementation only after explicit execute.
    from tools.gstreamer_audio_worker import load_gst
    from tools.gstreamer_audio_engine import GstAudioEngine,OUTPUT_CAPS
    gst,_=load_gst()
    jobs=PreparedPcmJobs(output_dir/'public-fixture',args.pcm,args.envelope)
    audio=FakesinkOutput(gst,GstAudioEngine,OUTPUT_CAPS,float(scenario.get('startup_silence_seconds',1.)))
    controller=pixels=video=worker=window=area=mailbox=None
    swap_times=deque(maxlen=240);candidate_launch_hashes={}
    errors=[];samples=[];commands=[];stages={};outcomes={}
    last_ui=0.;first_remote_target=None;first_received_time=None;last_packet=None
    previous_received=0.;previous_sequence=0.;measurement_start=None
    baseline_start_stats=None;baseline_end_stats=None;mode_counts={};mode_spans=[];event_index=0
    measurement_end=None;span_mode=None;span_start=None
    failed=False
    try:
        import gi
        gi.require_version('Gtk','3.0');gi.require_version('GdkX11','3.0')
        from gi.repository import Gtk,GLib,Gdk,GdkX11
        if not Gtk.init_check([])[0]:raise RuntimeError('Current X display unavailable')
        stages['gtk_import_seconds']=time.monotonic()-PROCESS_STARTED
        controller,pixels,background=create_controller(plan,audio,jobs,legacy_native_pixels=legacy)
        if legacy:
            offload_module=importlib.import_module('board.runtime.portrait_offload')
            # This constructor cannot connect to8796: preflight copied only the
            # isolated server port into a new in-memory config object.
            controller.portrait_offload=offload_module.PortraitOffload(plan['remote'],(423,438))
            video_module=importlib.import_module('tools.native_video')
            worker_module=importlib.import_module('tools.board_avatar_worker')
            for module,relative in ((offload_module,'board/runtime/portrait_offload.py'),
                (video_module,'tools/native_video.py'),(worker_module,'tools/board_avatar_worker.py')):
                if Path(module.__file__).resolve()!=plan['aura']/relative:raise ValueError('Wrong imported old module')
            video=video_module.NativeVideo(plan['aura']/'tools/libaura_pixels.so',(423,438))
            if args.backend=='old_nojpeg':worker_module.PreviewEncoder=NoPreviewEncoder
        else:
            modules=load_candidate_tools(candidate_paths)
            worker_module=modules['board_avatar_worker'];native_module=modules['native_yuki']
            mailbox,validated=native_module.prepare_portrait(candidate_aura,candidate_config,audio,candidate_launch_hashes)
            if validated is None:raise ValueError('Candidate source-profile validation failed: '+mailbox.error)
            controller.portrait_offload=mailbox
        worker=worker_module.AvatarRenderWorker(controller,background,(423,438),1/24,
            native_video=video,visual_fps=16,performance_path=output_dir/'pipeline-push-performance.jsonl')
        if args.backend=='old_nojpeg':
            if not isinstance(worker.preview_encoder,NoPreviewEncoder) or not worker.preview_encoder or worker.presenter is None or pixels is None:
                raise RuntimeError('NoJPEG control did not preserve truthy encoder/native presenter/pixels')
            check['source_patches'][0]['applied_and_constructor_checked']=True
        stages['core_native_pixels_prewarm_worker_ready_seconds']=time.monotonic()-PROCESS_STARTED
        window=Gtk.Window();window.set_title('AURA paired '+('C remote16 noJPEG' if args.backend=='old_nojpeg' else 'A remote16' if legacy else 'B Yuki16')+' TEST')
        window.set_decorated(False);window.set_skip_taskbar_hint(True);window.set_skip_pager_hint(True)
        window.set_accept_focus(False);window.set_focus_on_map(False);window.set_keep_above(bool(window_plan.get('keep_above',True)))
        window.set_resizable(False);window.set_default_size(423,438);window.move(x,y)
        if legacy:
            area=Gtk.DrawingArea()
            def mapped(widget):
                try:
                    handle=GdkX11.X11Window.get_xid(widget.get_window())
                    Gdk.Display.get_default().sync();video.attach(handle)
                    stages['sink_attached_seconds']=time.monotonic()-PROCESS_STARTED
                except Exception as error:errors.append(str(error));Gtk.main_quit()
            area.connect('map',mapped)
        else:
            area=native_module.create_gl_area(validated,mailbox,on_error=errors.append)
            # Correct swap-completion time without changing host code. This
            # small added diagnostic cost is charged to the candidate side.
            area.frame_observer=lambda stats:swap_times.append(stats['paint_at'])
            area.connect('map',lambda *_:stages.setdefault('native_area_mapped_seconds',time.monotonic()-PROCESS_STARTED))
        area.set_size_request(423,438);window.add(area)
        setup=time.monotonic()
        def poll():
            nonlocal last_ui,first_remote_target,first_received_time,last_packet,previous_received,previous_sequence
            nonlocal measurement_start,measurement_end,baseline_start_stats,baseline_end_stats,event_index,failed,span_mode,span_start
            try:
                now=time.monotonic()
                if errors:raise RuntimeError(errors[-1])
                if measurement_start is not None:
                    event_elapsed=now-measurement_start
                    while event_index<len(scenario['events']) and scenario['events'][event_index]['at']<=event_elapsed:
                        event=scenario['events'][event_index]
                        command_id=worker.request(event['method'],*event.get('args',[]))
                        commands.append(dict(index=event_index,event=event,command_id=command_id,
                            enqueued_monotonic=now,lateness_ms=(event_elapsed-event['at'])*1000))
                        event_index+=1
                # NativeVideo already measures its actual Gst identity handoff
                # in C. Do not add a per-frame Python observer or reconstruct
                # quantiles from this200ms snapshot polling cadence.
                interval=plan['config'].get('native_ui_tick_ms',200)/1000
                if now-last_ui<interval:return True
                last_ui=now;packet=worker.read();last_packet=packet
                display=(video.read() if video else swap_tail_stats(swap_times,mailbox.latest_stats,now))
                offload=packet['state'].get('portrait_offload',{})
                renderer=packet['state'].get('avatar_renderer',{})
                for item in renderer.get('command_results',[]):outcomes[item['command_id']]=item
                if mailbox and mailbox.error:raise RuntimeError('Candidate renderer fallback: '+mailbox.error)
                if packet['state'].get('error'):raise RuntimeError(packet['state']['error'])
                if display['received']<previous_received or display['sequence']<previous_sequence:raise RuntimeError('Native handoff counter rewound')
                previous_received=display['received'];previous_sequence=display['sequence']
                target_mode='remote' if legacy else 'native'
                if first_remote_target is None and offload.get('mode')==target_mode:
                    first_remote_target=packet['sequence'] if legacy else 0
                if (first_received_time is None and first_remote_target is not None and display['received']>0
                    and display['sequence']>=first_remote_target):
                    first_received_time=now
                    stages['first_observed_backend_handoff_seconds']=now-PROCESS_STARTED
                    stages['ready_polling_resolution_seconds']=interval
                    ready=dict(check,status='READY_WARMUP',stages=stages,ready_monotonic=first_received_time)
                    (output_dir/'ready.json').write_text(json.dumps(ready,indent=2),encoding='utf8')
                    print('PAIRED '+json.dumps(dict(status='READY_WARMUP',pid=os.getpid(),at=now)),flush=True)
                if first_received_time is None:
                    if now-setup>args.startup_timeout:raise RuntimeError('Matching backend first handoff timed out')
                    return True
                if measurement_start is None and now-first_received_time>=scenario['warmup_seconds']:
                    measurement_start=now;baseline_start_stats=dict(display)
                    stages['measurement_start_monotonic']=now
                    (output_dir/'measurement-ready.json').write_text(json.dumps(dict(pid=os.getpid(),at=now,
                        backend=check['backend'],source_mode=offload.get('mode'),scenario_sha256=check['scenario_sha256'])),encoding='utf8')
                if measurement_start is None:return True
                elapsed=now-measurement_start
                # Intent scheduling above keeps10ms cadence; expensive public
                # snapshots below retain the actual old200ms UI cadence.
                mode=offload.get('mode','unknown');mode_counts[mode]=mode_counts.get(mode,0)+1
                if span_mode is None:span_mode=mode;span_start=measurement_start
                elif span_mode!=mode:
                    mode_spans.append(dict(mode=span_mode,start_monotonic=span_start,end_monotonic=now,seconds=now-span_start))
                    span_mode=mode;span_start=now
                samples.append(dict(at=now,elapsed=elapsed,source_mode=mode,display=display,
                    worker_sequence=packet['sequence'],worker_render_ms=packet['render_ms'],
                    worker_timings=packet.get('timings_ms'),phase=packet['state'].get('phase'),
                    presentation=packet['state'].get('avatar_renderer',{}).get('presentation'),
                    worker_profile=packet['state'].get('avatar_renderer',{}).get('profile'),
                    state=packet['state'].get('state'),playing=packet['state'].get('playing'),
                    command_pending=packet['state'].get('avatar_command_pending'),
                    paused=packet['state'].get('paused'),audio_time=packet['state'].get('audio_time'),
                    speech_gain=packet['state'].get('speech_gain'),mouth_level=packet['state'].get('mouth_level'),
                    portrait=offload,jpeg_bytes=len(packet.get('jpeg') or b''),
                    native_stats=dict(mailbox.latest_stats) if mailbox else None,
                    audio=audio.cached_snapshot()))
                baseline_end_stats=dict(display)
                if elapsed>=scenario['duration_seconds']:
                    measurement_end=now;stages['measurement_end_monotonic']=now
                    Gtk.main_quit();return False
                return True
            except Exception as error:
                errors.append(type(error).__name__+': '+str(error));failed=True;Gtk.main_quit();return False
        window.show_all();GLib.timeout_add(10,poll)
        Gtk.main()
    except Exception as error:errors.append(type(error).__name__+': '+str(error));failed=True
    finally:
        if measurement_start is not None and measurement_end is None:
            measurement_end=time.monotonic();stages['measurement_end_monotonic']=measurement_end
        if span_mode is not None:
            mode_spans.append(dict(mode=span_mode,start_monotonic=span_start,end_monotonic=measurement_end,seconds=measurement_end-span_start))
        # Same ownership order as production: stop the worker/presenter before
        # destroying its video sink. Keep the XID alive until the sink closes.
        for label,resource in (('worker',worker),('video',video),('pixels',pixels),('audio',audio)):
            if resource:
                try:resource.close()
                except Exception as error:errors.append(label+' cleanup: '+str(error));failed=True
        if window:window.destroy()
    for command in commands:command['outcome']=outcomes.get(command['command_id'])
    report=dict(check,status='COMPLETE' if not errors else 'FAIL',stages=stages,errors=errors,
        samples=len(samples),events_enqueued=event_index,mode_counts=mode_counts,
        mode_spans=mode_spans,mode_observation='200ms public snapshot sampling; transitions bounded by polling cadence, not exact render-frame mode',
        strict_backend_mode_entire_measurement=bool(mode_counts) and set(mode_counts)==({'remote'} if legacy else {'native'}),
        cold_definition='new board process/provenance file hashing/import/backend setup through first observed matching-mode handoff at the same200ms UI poll cadence; B also hashes yuki-root proof before the real prepare_portrait validation; OS page cache not cleared',
        warm_definition='same process after first observed matching backend handoff plus scenario warmup; independent Windows server already ready throughout ABBA',
        native_interval_definition=dict(times=240,intervals=239,
            p95='sorted[min(n-1,size_t(n*.95))]',p99='sorted[min(n-1,size_t(n*.99))]',
            measurement=('GStreamer identity callback entry before its lock/ximagesink' if legacy else 'EGL swap completion')+'; tail window, not physical scanout'),
        start_display=baseline_start_stats,end_display=baseline_end_stats,
        windows_server=plan['proof'],streaming_business='public prerecorded PCM uses RealtimeController, no network/model speech path',
        source_roles='A real old remote/worker/presenter/JPEG/video; C identical A except process-local truthy no-op PreviewEncoder; B real new worker/LocalPortrait/EGL; common controller/PCM; full UI/camera/identity/ASR/mechanical services excluded symmetrically by coordinator',
        feature_difference_note='A-B measures total replacement pipeline. A-C estimates JPEG encoder/thread/queue impact in the old pipeline. C-B excludes JPEG generation on both sides but still differs in remote transport/presenter/Gst versus native EGL, snapshot cadence and initialization; it does not isolate pure rendering CPU.')
    report['candidate_launch_hashes']=candidate_launch_hashes
    if legacy:report['strict_remote_mode_entire_measurement']=report['strict_backend_mode_entire_measurement']
    mode_seconds={}
    for span in mode_spans:mode_seconds[span['mode']]=mode_seconds.get(span['mode'],0)+span['seconds']
    report['observed_mode_seconds']=mode_seconds
    duration=(measurement_end-measurement_start) if measurement_start is not None and measurement_end is not None else None
    report['measurement_duration_seconds']=duration
    target_mode='remote' if legacy else 'native'
    report['observed_target_mode_fraction']=mode_seconds.get(target_mode,0)/duration if duration else None
    report['mode_validity_note']='A local transitions during submit/cancel/state resync are preserved production behavior; strict_remote=false alone does not invalidate a run. Inspect transition spans, offload errors/counters and recovery. B renderer failure remains fatal.'
    report['command_outcomes_observed']=len(outcomes)
    report['command_failures']=[item for item in outcomes.values() if not item.get('ok')]
    if samples and baseline_start_stats and baseline_end_stats:
        report['received_during_measurement']=baseline_end_stats['received']-baseline_start_stats['received']
        report['handoff_fps_over_measurement']=report['received_during_measurement']/duration if duration and duration>0 else None
    (output_dir/'summary.json').write_text(json.dumps(report,ensure_ascii=True,indent=2),encoding='utf8')
    (output_dir/('old-nojpeg-summary.json' if args.backend=='old_nojpeg' else 'old-summary.json' if legacy else 'new-summary.json')).write_text(json.dumps(report,ensure_ascii=True,indent=2),encoding='utf8')
    (output_dir/'samples.json').write_text(json.dumps(samples,ensure_ascii=True),encoding='utf8')
    (output_dir/'commands.json').write_text(json.dumps(commands,ensure_ascii=True,indent=2),encoding='utf8')
    if swap_times:(output_dir/'swap-tail240.json').write_text(json.dumps(list(swap_times)),encoding='utf8')
    print('PAIRED '+json.dumps(report,ensure_ascii=True),flush=True)
    return 2 if failed or errors else 0

if __name__=='__main__':raise SystemExit(main())
