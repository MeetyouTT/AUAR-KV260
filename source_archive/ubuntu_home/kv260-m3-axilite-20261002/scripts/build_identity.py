#!/usr/bin/env python3
"""Generate the M3 source identity before packaging; performs no board operation."""
from pathlib import Path
from datetime import datetime, timezone
import hashlib
import json
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SOURCE_NAMES = [
    "rtl/aura_m3_regs.v",
    "scripts/package_m3.tcl",
    "scripts/integrate_m3.tcl",
    "scripts/build_identity.py",
    "src/kv260/platforms/vivado/kv260_ispMipiRx_vcu_DP/scripts/main.tcl",
    "src/kv260/platforms/vivado/kv260_ispMipiRx_vcu_DP/scripts/config_bd.tcl",
    "src/kv260/overlays/examples/benchmark/dpu_conf.vh",
    "src/kv260/overlays/examples/benchmark/prj_conf/prj_config_1dpu",
    "src/kv260/overlays/examples/benchmark/kernel_xml/dpu/kernel.xml",
    "src/kv260/overlays/examples/benchmark/scripts/bip_proc.tcl",
    "src/kv260/overlays/examples/benchmark/scripts/package_dpu_kernel.tcl",
]


def main():
    commit = subprocess.run(
        ["git", "-C", str(ROOT / "src"), "rev-parse", "HEAD"],
        check=True, text=True, capture_output=True,
    ).stdout.strip()
    inputs = [{"path": name, "sha256": hashlib.sha256((ROOT / name).read_bytes()).hexdigest()}
              for name in SOURCE_NAMES]
    descriptor = {"reference_commit": commit, "base_address": "0x80080000",
                  "range": "0x1000", "clock_hz": 100000000, "inputs": inputs}
    digest = hashlib.sha256(json.dumps(descriptor, sort_keys=True).encode()).hexdigest()
    build_id = digest[:8]
    header = ("// Generated by scripts/build_identity.py; regenerate after source changes.\n"
              "`ifndef AURA_M3_BUILD_ID_VH\n`define AURA_M3_BUILD_ID_VH\n"
              f"`define AURA_M3_BUILD_ID 32'h{build_id}\n`endif\n")
    (ROOT / "rtl/m3_build_id.vh").write_text(header)
    descriptor.update({"generated_at_utc": datetime.now(timezone.utc).isoformat(),
                       "source_identity_sha256": digest, "build_id": "0x" + build_id,
                       "meaning": "First 32 bits of the source/configuration digest; full digest in this file"})
    (ROOT / "evidence/build_identity.json").write_text(
        json.dumps(descriptor, ensure_ascii=False, indent=2) + "\n")
    print("M3 source BUILD_ID:", "0x" + build_id)


if __name__ == "__main__":
    main()
