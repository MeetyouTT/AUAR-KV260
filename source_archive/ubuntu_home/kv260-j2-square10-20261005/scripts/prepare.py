#!/usr/bin/env python3
"""Reuse reviewed M3 AXI interface declarations, without altering that project."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARENT = Path('/home/ghmd/kv260-m3-axilite-20261002/rtl/aura_m3_regs.v')
body = (ROOT / 'rtl/axi_body.sv.in').read_text()
source = PARENT.read_text()
ports = source.split('module aura_m3_regs (', 1)[1].split('\n);', 1)[0]
ports = ports.replace('input wire s_axi_rready',
                      'input wire s_axi_rready,\n    output wire servo_pwm')
inputs = [ROOT / 'rtl/pwm_burst.sv', ROOT / 'rtl/axi_body.sv.in',
          ROOT / 'scripts/prepare.py', PARENT]
hashes = {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}
identity = hashlib.sha256(json.dumps(hashes, sort_keys=True).encode()).hexdigest()
head = ('`timescale 1ns/1ps\n'
        '// AXI declarations derived from the preserved AURA M3 source.\n'
        '// Generated by scripts/prepare.py; bench ABI is separate from motion ABI.\n'
        'module aura_pwm_probe #(\n'
        '    parameter integer CLK_HZ = 99999001,\n'
        '    parameter integer PWM_HZ = 10,\n'
        '    parameter integer PULSE_US = 50000,\n'
        '    parameter integer RUN_FRAMES = 0,\n'
        f"    parameter [31:0] BUILD_ID = 32'h{identity[:8]}\n"
        ') (')
out = ROOT / 'rtl/aura_pwm_probe.sv'
out.write_text(head + ports + '\n);\n' + body)
(ROOT / 'board/bench_config.h').write_text(
    f'#define BENCH_BUILD_ID 0x{identity[:8]}u\n'
    '#define BENCH_RUN_FRAMES 0u\n'
    '#define BENCH_PERIOD_TICKS 9999900u\n'
    '#define BENCH_PULSE_TICKS 4999950u\n'
    '#define BENCH_PULSE_US 50000u\n'
    '#define BENCH_FIRMWARE_NAME "aura_square10.bit.bin"\n')
(ROOT / 'evidence').mkdir(exist_ok=True)
(ROOT / 'evidence/source_identity.json').write_text(json.dumps({
    'identity_sha256': identity, 'build_id': identity[:8], 'inputs': hashes,
    'generated_rtl_sha256': hashlib.sha256(out.read_bytes()).hexdigest(),
    'parent_modified': False}, indent=2) + '\n')
print(json.dumps({'build_id': identity[:8], 'generated': str(out)}))
